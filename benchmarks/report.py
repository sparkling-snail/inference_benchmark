"""
Recipe table: one Markdown table per model, cheapest passing config first.
"""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path
from typing import Any

from .recipe import load_recipes, recipe_relpath

HEADER = (
    "| config | GPUs | goodput (req/s) | out tok/s | tok/s/GPU | p99 TTFT (ms) | p99 ITL (ms) | $/1M out tok | quality |\n"
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"
)


def render(recipes: list[dict[str, Any]]) -> str:
    if not recipes:
        return "_No recipes yet._\n"
    by_model: dict[str, list[dict]] = defaultdict(list)
    for r in recipes:
        by_model[r["model"]["id"]].append(r)

    out = []
    for model, all_rs in sorted(by_model.items()):
        rs = sorted((r for r in all_rs if _status(r) != "fail"), key=_sort_key)
        failed = sorted((r for r in all_rs if _status(r) == "fail"), key=lambda r: r["name"])
        slo = all_rs[0]["slo"]
        out.append(f"### {model}\n")
        priced = any((r.get("envelope") or {}).get("usd_per_1m_output_tokens") is not None for r in rs)
        order = "cost at that SLO" if priced else "output tokens/s per GPU at that SLO (no prices recorded)"
        out.append(f"SLO: p99 TTFT ≤ {slo['ttft_p99_ms']:g} ms, p99 ITL ≤ {slo['itl_p99_ms']:g} ms, "
                   f"errors ≤ {slo['max_error_rate']:.0%}. Sorted by {order}.\n")
        out.append(HEADER)
        out.extend(_row(r) for r in rs)
        out.append("")
        if failed:
            out.append("Excluded by the accuracy gate (score dropped too far below the BF16 baseline):\n")
            out.extend(f"- {_link(r)}: {_drop_text(r)}" for r in failed)
            out.append("")
    return "\n".join(out) + "\n"


def write_report(recipes_dir: Path, out_path: Path | None = None) -> Path:
    out_path = out_path or recipes_dir / "README.md"
    body = render(load_recipes(recipes_dir))
    out_path.write_text(
        "# Recipes\n\n"
        "Generated by `python -m benchmarks report`. Each row links to its recipe file; "
        "goodput is the highest Poisson arrival rate that met the SLO.\n\n" + body
    )
    return out_path


def _status(r: dict) -> str:
    return (r.get("quality") or {}).get("status", "-")


def _link(r: dict) -> str:
    rel = recipe_relpath(r["model"]["id"], r["name"])
    return f"[{rel.stem}]({rel.as_posix()})"


def _drop_text(r: dict) -> str:
    q = r["quality"]
    drops = ", ".join(f"{t} {-d:+.1f} pts" for t, d in q.get("drop_pts", {}).items())
    return f"{drops} vs {q.get('baseline', 'baseline')} (limit {q.get('max_drop_pts'):g} pts)"


def _quality_cell(r: dict) -> str:
    q = r.get("quality") or {}
    status = q.get("status", "-")
    if status in ("pass", "fail", "inconclusive") and q.get("drop_pts"):
        task = max(q["drop_pts"], key=q["drop_pts"].get)  # the worst task
        change = round(-q["drop_pts"][task], 1) + 0.0  # + 0.0 turns -0.0 into 0.0
        ci = (q.get("ci_pts") or {}).get(task)
        return f"{status} ({change:+.1f}" + (f" ± {ci:.1f}" if ci else "") + " pts)"
    return status


def _row(r: dict) -> str:
    cfg = _link(r)
    env = r.get("envelope")
    quality = _quality_cell(r)
    if not env:
        return f"| {cfg} | {r['topology']['gpus']} | ✗ none | - | - | - | - | - | {quality} |"
    capped = "≥" if env.get("capped_at_max_rate") else ""
    return (
        f"| {cfg} | {r['topology']['gpus']} | {capped}{env['goodput_rps']:g} | {env['output_tokens_per_s']:g} "
        f"| {env['output_tokens_per_s_per_gpu']:g} | {_fmt(env['ttft_ms']['p99'])} | {_fmt(env['itl_ms']['p99'])} "
        f"| {_fmt(env['usd_per_1m_output_tokens'], 3)} | {quality} |"
    )


def _sort_key(r: dict):
    """Cheapest first; without prices, highest throughput per GPU (cost-proportional) first."""
    env = r.get("envelope") or {}
    cost = env.get("usd_per_1m_output_tokens")
    return (cost is None, cost or 0.0, -(env.get("output_tokens_per_s_per_gpu") or 0.0), r["name"])


def _fmt(x: float | None, digits: int = 1) -> str:
    return "-" if x is None else f"{x:.{digits}f}"
